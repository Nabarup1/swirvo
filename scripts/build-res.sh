#!/usr/bin/env bash
# Compile the Windows resource (app icon + version info) linked into Swirvo.exe and
# swirvo-cli.exe: packaging/icon/swirvo.res. The .res is committed, so normal builds
# don't need this; rerun it after changing the icon (crates/render/src/icon.rs, then
# `cargo run -p swirvo-render --example icon_assets`) or the version in Cargo.toml.
#
# Needs the Windows SDK's rc.exe on the Windows side (Visual Studio Build Tools).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
rc="$(ls "/mnt/c/Program Files (x86)/Windows Kits/10/bin/"*/x64/rc.exe 2>/dev/null | sort -V | tail -1 || true)"
[[ -n "$rc" ]] || { echo "rc.exe not found (install the Windows SDK)" >&2; exit 1; }
ver="$(grep -m1 '^version' "$root/Cargo.toml" | sed -E 's/.*"([0-9]+)\.([0-9]+)\.([0-9]+)".*/\1 \2 \3/')"
read -r major minor patch <<<"$ver"
publisher="$(grep -m1 '^PUBLISHER_DISPLAY_NAME=' "$root/packaging/msix/identity.env" 2>/dev/null | cut -d= -f2- | tr -d '"' || true)"
publisher="${publisher:-[Publisher]}"
# rc.exe runs on Windows; work in a Windows temp folder and copy the result back.
tmp="$(cmd.exe /c 'echo %TEMP%' 2>/dev/null | tr -d '\r')\\swirvo-res"
wtmp="$(wslpath -u "$tmp")"
rm -rf "$wtmp" && mkdir -p "$wtmp"
cp "$root/packaging/icon/swirvo.ico" "$wtmp/swirvo.ico"
cat > "$wtmp/swirvo.rc" <<RC
// Generated by scripts/build-res.sh. No headers: constants are written out.
1 ICON "swirvo.ico"

1 VERSIONINFO
FILEVERSION ${major},${minor},${patch},0
PRODUCTVERSION ${major},${minor},${patch},0
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName", "${publisher}"
            VALUE "FileDescription", "Swirvo: drag, tap, convert"
            VALUE "FileVersion", "${major}.${minor}.${patch}.0"
            VALUE "InternalName", "Swirvo"
            VALUE "LegalCopyright", "\xA9 2026 ${publisher}"
            VALUE "OriginalFilename", "Swirvo.exe"
            VALUE "ProductName", "Swirvo"
            VALUE "ProductVersion", "${major}.${minor}.${patch}.0"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
RC
(cd "$wtmp" && "$rc" /nologo /c 1252 /fo swirvo.res swirvo.rc)
cp "$wtmp/swirvo.rc" "$root/packaging/icon/swirvo.rc"
cp "$wtmp/swirvo.res" "$root/packaging/icon/swirvo.res"
rm -rf "$wtmp"
echo "wrote packaging/icon/swirvo.res ($(stat -c %s "$root/packaging/icon/swirvo.res") bytes)"

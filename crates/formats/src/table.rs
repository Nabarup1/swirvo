//! The format table. Order is irrelevant; ids are assigned densely at registry build.

use swirvo_core::{Category as C, Traits as T};

#[derive(Debug, Clone, Copy)]
pub struct FormatDef {
    /// Stable key used by capabilities and the CLI ("heic", "tar.gz").
    pub key: &'static str,
    pub name: &'static str,
    pub category: C,
    /// First extension is the one used for outputs.
    pub exts: &'static [&'static str],
    pub mime: &'static str,
    pub traits: T,
}

const fn f(
    key: &'static str,
    name: &'static str,
    category: C,
    exts: &'static [&'static str],
    mime: &'static str,
    traits: T,
) -> FormatDef {
    FormatDef {
        key,
        name,
        category,
        exts,
        mime,
        traits,
    }
}

